CREATE TABLE stock_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id),
    quantity BIGINT NOT NULL CHECK (quantity >= 0),
    CONSTRAINT stock_balances_product_warehouse_key UNIQUE (product_id, warehouse_id)
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    balance_id BIGINT NOT NULL REFERENCES stock_balances(id),
    actor_id BIGINT NOT NULL REFERENCES app_users(id),
    type VARCHAR(20) NOT NULL CHECK (type IN
        ('INITIAL_ENTRY', 'ENTRY', 'EXIT', 'ADJUSTMENT_IN', 'ADJUSTMENT_OUT')),
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    previous_balance BIGINT NOT NULL CHECK (previous_balance >= 0),
    new_balance BIGINT NOT NULL CHECK (new_balance >= 0),
    reason VARCHAR(500),
    occurred_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT stock_movements_adjustment_reason CHECK (
        type NOT IN ('ADJUSTMENT_IN', 'ADJUSTMENT_OUT')
        OR (reason IS NOT NULL AND btrim(reason) <> '')
    )
);

CREATE INDEX stock_movements_balance_occurred_at_idx
    ON stock_movements (balance_id, occurred_at DESC, id DESC);
